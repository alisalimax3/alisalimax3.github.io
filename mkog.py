import zlib, struct
W,H=1200,630
buf=bytearray(W*H*3)
def px(x,y,c):
    if 0<=x<W and 0<=y<H:
        i=(y*W+x)*3; buf[i]=c[0]; buf[i+1]=c[1]; buf[i+2]=c[2]
def rect(x0,y0,x1,y1,c):
    for y in range(y0,y1):
        for x in range(x0,x1): px(x,y,c)
def circle(cx,cy,r,c):
    for y in range(cy-r,cy+r+1):
        for x in range(cx-r,cx+r+1):
            if (x-cx)**2+(y-cy)**2<=r*r: px(x,y,c)
def tri(a,b,d,c):
    def s(p,q,r): return (p[0]-r[0])*(q[1]-r[1])-(q[0]-r[0])*(p[1]-r[1])
    for y in range(min(a[1],b[1],d[1]),max(a[1],b[1],d[1])+1):
        for x in range(min(a[0],b[0],d[0]),max(a[0],b[0],d[0])+1):
            d1=s(a,b,(x,y)); d2=s(b,d,(x,y)); d3=s(d,a,(x,y))
            if not(((d1<0)or(d2<0)or(d3<0)) and ((d1>0)or(d2>0)or(d3>0))): px(x,y,c)
def glow(cx,cy,R,c,k):
    for y in range(max(0,cy-R),min(H,cy+R)):
        for x in range(max(0,cx-R),min(W,cx+R)):
            dd=((x-cx)**2+(y-cy)**2)**0.5
            if dd<R:
                a=k*(1-dd/R)**2; i=(y*W+x)*3
                buf[i]=int(buf[i]*(1-a)+c[0]*a); buf[i+1]=int(buf[i+1]*(1-a)+c[1]*a); buf[i+2]=int(buf[i+2]*(1-a)+c[2]*a)
